"""발화 인용 검사 — **결정 기록은 사람 말을 그대로 담지 않는다**(DECISIONS §199).

★ **seshat `tools/check_speech.py` 의 축을 옮긴 것이다**(거기 §199). 재 본 수는 그쪽 것이다 —
  이 저장소에서는 말투 1 · 욕설 0 이었다.

  python3 tools/check_speech.py            DECISIONS · PLAN · MASTER 를 본다
  python3 tools/check_speech.py --selftest 합성 입력으로 이 자를 문다

### 무엇을 묻나

**「사람 말을 그대로 옮겼나」 하나다.** 욕이 들었나가 아니다 — 실측으로 이 저장소의
일곱 자리 중 **욕설은 둘뿐**이었고, 나머지 다섯은 거친 말이 한 글자도 없는데 똑같이
들어가면 안 되는 글이었다. **욕설 사전을 세웠으면 다섯을 놓친다.**

★ **낱말 목록으로 가르지 않는다**(§167 의 그 말). 대신 **종결 어미**를 본다 — 해체
  종결(`거야` · `잖아` · `했어`)과 해체 의문, 그리고 채팅 기호(`??` · `;;` · `ㅋ`)다.
  **이것은 사전이 아니라 닫힌 문법 부류다** — 욕설은 끝없이 생기지만 한국어 종결 어미는
  유한하고, 기록의 평어체와 **문법으로** 갈린다.

### 발화 동사로는 안 잡는다

하토르가 그 길을 먼저 재고 버렸다(하토르 D-0438) — 「사용자가 물었다 — "…"」 꼴을
세어 보니 **50건 중 25건이 오탐**이었다. 기록 인용 · 화면 문구 · 오류 메시지까지 물었다.
**경보가 반이 거짓이면 사람이 끈다.** 그래서 **무엇이 인용됐는지는 안 보고 말투만 본다** —
`§124 가 「검사기만으로는 보상이 안 된다」 고 적었다` 는 평어체라 안 걸리고,
`「뭔소리야 고쳐야지」` 는 걸린다. **인용 부호의 종류도 안 가린다.**

### 탈출구 — 발화가 자료인 자리

**귀 판정은 원문이 측정값이다.** 「왠지 모르겠는데 별로」 를 「부정적으로 평했다」 로
옮기면 **자료가 사라진다.** 그런 자리는 줄에 `<!--말-ok-->` 를 단다.

★ **탈출구를 쓴 자리는 세어서 찍는다.** 조용히 면제되면 **면제가 풍경이 된다**(§290).

### 소급 바닥이 없다

**전수 0건이다.** 바닥을 두면 「과거는 안 본다」 가 되고, 그러면 다음 판이 옛 절을
손볼 때 구어가 다시 들어온다. §199 가 일곱 자리를 간접 서술로 옮기면서 0 으로 만들었다.
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
문서 = ("docs/DECISIONS.md", "docs/PLAN.md", "docs/MASTER.md", "README.md")
말OK = "<!--말-ok-->"

구어 = (
    # 채팅 기호
    r";;|ㅋ|ㅠ|ㅡㅡ|\?\?|\?!"
    # 해체 의문 — **평어체 의문은 안 잡는다**(`~는가?` · `~인가?` 는 기록의 말이다)
    r"|(?<![가-힣])(?:맞아|맞지|되지|하지|할래|그치|뭐야|뭐지|뭔데|어때)\s*\?"
    r"|아니야\?|거야\?|건데\?|인데\?|는데\?|냐\?|니\?|맞나\?"
    # 해체 종결 — 경계를 붙인다(`하네스` 가 `하네` 에 걸렸다 · 하토르 실측)
    r"|거야|거임|거네|잖아|는걸|했어|했네|하네(?![가-힣])|이네|싫어|더라(?![가-힣])"
    # ★ **`못한다` · `해라` · `구해라` 를 넣었다가 뺐다.** 평어체 보통 말이다 —
    #   「재현하지 **못한다**」 · 「`doctor` 로 확인**해라**」 가 걸려 thoth 에서 **6 중 3 이
    #   거짓**이 됐다. 하토르가 자른 그 선(반이 거짓이면 끈다)에 그대로 걸린다.
    #   `야지` 만 남긴다 — 양쪽 저장소 인용 3,312 중 **1 적중 · 0 오탐**이다.
    r"|야지(?![가-힣])"
    # 구어 의문
    r"|아니냐|않나|아님\?|하자고|니까\?|뭔[말소]"
)
"""인용 안에서 막는 꼴. **갈래마다 세어서 넣는다** — 오탐이 하나라도 나오면 경계를 붙인다."""

욕 = re.compile(r"(좆|씨발|시발|존나|지랄|개새|병신|미친|미췬|닥쳐|엿먹)")
"""**받치는 그물이지 주축이 아니다.** 실측 : seshat 인용 1,749 중 말투가 14 를 물고
   이것이 **1** 을 더 문다 — `「… 퍼플렉시티는 좆밥이냐」`. 그 하나는 **`?` 없는 해체
   의문**이라 말투로는 못 가른다 — `「사람이냐」` · `「어느 디렉터리냐」` 같은 **개념
   이름표**와 문법이 똑같다. 거기까지 바닥을 내리면 **오탐이 78%** 다.

★ **그러니 사전을 주축에 두지 않는다**(§167). 주축으로 쓰면 15 중 1 만 잡는다 —
  나머지 열넷은 거친 말이 한 글자도 없는데 똑같이 들어가면 안 되는 글이다.
★ **`꺼져` 를 뺐다.** 「`ollama` 가 **꺼져** 있으면」 이 네 번 걸렸다 — 꺼지다는
  보통 낱말이다. **낱말 하나가 그물을 소음으로 만든다.**"""

인용 = re.compile(r'[「“"]([^」”"\n]{2,}(?:\n[^」”"\n]*){0,4}?)[」”"]')
"""인용 덩어리. **네 줄까지 넘는다** — 줄 단위로 보면 두 줄짜리를 놓친다(하토르 D-0438).
   이 저장소에서 실제로 그랬다 : §199 를 쓰기 전 줄 단위로 세어 **일곱 중 둘을 놓쳤다**."""

인용줄 = re.compile(r"^>\s+(.+)$")
"""`> ` 블록도 인용이다. 실측 일곱 중 **다섯**이 이 꼴이었다."""

절머리 = re.compile(r"^## §(\d+)\.", re.M)
건너뜀 = re.compile(r"^(?:    |\t|```)")
"""안 보는 줄. **들여쓴 블록은 산문이 아니다** — 코드와 출력이다."""


def _줄자리(글: str) -> list[int]:
    자리 = [0]
    for 줄 in 글.splitlines():
        자리.append(자리[-1] + len(줄) + 1)
    return 자리


def _줄번호(자리: list[int], 위치: int) -> int:
    낮, 높 = 0, len(자리) - 1
    while 낮 < 높 - 1:
        가운데 = (낮 + 높) // 2
        if 자리[가운데] <= 위치:
            낮 = 가운데
        else:
            높 = 가운데
    return 낮


def 발화(글: str) -> tuple[list[tuple[int, str]], int]:
    """`([(줄 번호, 인용)], 면제 수)`. **빈 목록이 통과다.**"""
    줄들 = 글.splitlines()
    자리 = _줄자리(글)
    난것: list[tuple[int, str]] = []
    면제 = 0

    def 본다(첫: int, 끝: int, 속: str) -> None:
        nonlocal 면제
        if 건너뜀.match(줄들[첫]):
            return
        한줄 = " ".join(속.split())
        if not (re.search(구어, 한줄) or 욕.search(한줄)):
            return
        if any(말OK in 줄들[i] for i in range(첫, min(끝, len(줄들) - 1) + 1)):
            면제 += 1
            return
        난것.append((첫 + 1, 한줄))

    for m in 인용.finditer(글):
        본다(_줄번호(자리, m.start()), _줄번호(자리, m.end() - 1), m.group(1))
    for i, 줄 in enumerate(줄들):
        m = 인용줄.match(줄)
        if m:
            본다(i, i, m.group(1))
    return 난것, 면제


def 절(글: str, 줄: int) -> str:
    """그 줄이 선 절. **어느 절인지 안 적으면 못 찾는다.**"""
    줄들 = 글.splitlines()
    for i in range(min(줄, len(줄들)) - 1, -1, -1):
        m = 절머리.match(줄들[i])
        if m:
            return f"§{m.group(1)}"
    return "(머리말)"


def _canary() -> None:
    """★ **도구가 고장났나**를 이 자가 묻는다 — 안 물면 조용히 통과한다(§287)."""
    난것, _ = 발화('사람이 「이거 왜 안되는거야」 라고 했다')
    if not 난것:
        raise SystemExit("2: 카나리아가 안 울었다 — 구어 꼴이 늙었다")
    if 발화("§1 이 「값을 두 곳에 적지 않는다」 고 적었다")[0]:
        raise SystemExit("2: 카나리아가 평어체 기록 인용을 물었다 — 오탐이다")
    if not 발화("물음이 왔다 — 「저것들은 좆밥이냐」")[0]:
        raise SystemExit("2: 받치는 그물이 안 울었다 — 말투로 못 가르는 자리다")
    if 발화("`ollama` 가 「꺼져 있으면」 한 줄로 말한다")[0]:
        raise SystemExit("2: 보통 낱말을 물었다 — 그물이 소음이 됐다")


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    _canary()
    if "--selftest" in args:
        print("    카나리아 통과 — 구어는 물고 평어체 기록 인용은 안 문다")
        return 0
    난것: list[str] = []
    면제들 = 0
    for rel in 문서:
        p = ROOT / rel
        if not p.is_file():
            continue
        글 = p.read_text(encoding="utf-8")
        것, 면제 = 발화(글)
        면제들 += 면제
        난것 += [f"{rel}:{n} {절(글, n)} — {q[:76]}" for n, q in 것]
    for f in 난것:
        print(f"    {f}")
    if 난것:
        print(f"    구어 인용 {len(난것)}곳 — 간접 서술로 옮긴다"
              f"(「사용자가 ~를 지적했다」). 발화가 자료인 자리면 {말OK}")
        return 1
    print(f"  구어 인용 0곳 · 면제 {면제들}곳")
    return 0


if __name__ == "__main__":
    # ★ **맨몸으로 두지 않는다**(seshat DECISIONS §232). 뜻밖의 예외가 역추적으로 나가면
    #   부르는 쪽은 **위반과 고장을 못 가른다** — 고장은 2 로 끝낸다.
    try:
        sys.exit(main())
    except SystemExit:
        raise
    # 넓게 잡는 자리다 — **고장을 2 로 번역하는 것이 이 블록의 일이다**.
    # `noqa` 를 안 단다 : 이 저장소의 ruff 는 `BLE` 를 안 켜서 **쓰이지 않는 noqa**
    # 가 되고 `RUF100` 이 운다(§196 에서 `E402` 로 같은 일을 했다).
    except Exception as e:
        print(f"    check_speech 가 죽었다 — {type(e).__name__}: {e}", file=sys.stderr)
        sys.exit(2)
