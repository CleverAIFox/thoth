#!/usr/bin/env bash
# playwright 판을 **한 곳에서** 못 박는다(DECISIONS §194).
#
# ★ **이 파일은 `.` 으로 들여오는 것이고 실행하는 것이 아니다.** 그래도 `env.sh` ·
#   `infra.sh` 와 같이 셔뱅을 단다 — shellcheck 가 **어느 셸로 읽을지 모르면 SC2148 로
#   거절**하고, 이 저장소의 lib 셸 셋이 서로 다른 꼴이면 다음 사람이 어느 쪽이 규약인지
#   못 안다. 셋 다 같은 꼴이 규약이다.
#
# ★ **안 박으면 매번 최신이 온다.** `uv run --with playwright` 는 부를 때마다 **그 순간의
#   최신**을 푼다. 그런데 브라우저는 `~/.cache/ms-playwright/` 에 **빌드 번호로** 깔려
#   있어서, 판이 올라가는 날 **깔린 것과 어긋나고 빌드가 죽는다.**
#   2026-10-15 에 실제로 그랬다 — 기획서 굽기가 멈췄고 191MB 를 다시 받았다.
#
# ★ **재서 골랐다.** 판과 크로미움 빌드의 대응을 직접 재 봤다 :
#       1.56.0 → 1194 · 1.57.0 → 1200 · 1.58.0 → 1208 · 1.59.0 → 1217
#       1.60.0 → 1223 · 1.63.0 → 1243 · **1.64.0 → 1248** · 1.65.0 없음
#   `1248` 이 이 기계에 깔린 것이므로 **다시 안 받는다.**
#
# ★ **늙는다 — 그것이 설계다.** 판을 올리는 것은 **한 줄을 고치는 일**이어야 하지,
#   어느 날 아침 빌드가 죽는 일이면 안 된다(액션을 SHA 로 박고 `npm ci` 를 쓰는 것과 같다).
#   올릴 때는 이 줄만 고치고 `python -m playwright install chromium` 을 한 번 돌린다.
#
# ★ **이 눈 밖 — CI 에는 브라우저가 아예 없다.** 러너는 `~/.cache/ms-playwright` 가 비어
#   있어 캐스케이드 검사가 건너뛰어진다. 그 건너뜀은 `check_skips` 에 선언돼 있고,
#   그 자리를 막는 것은 이 핀이 아니라 **CI 에 설치 단계를 두는 일**이다 — 판마다 120MB 를
#   받는 값이 그 검사의 값보다 큰지 **아직 안 쟀다.**
#
# ★ **SC2034「안 쓰는 변수」 는 여기서 거짓이다.** 이 변수를 쓰는 곳은 **정의상 다른
#   파일**이다 — 들여오는 쪽(`build_proposal.sh` · `doctor.sh` · `ci.yml`)이 쓴다.
#   `export` 로 바꿔 린터를 달래지 않는다 : 린터를 위해 **실행 동작을 바꾸는 것**은
#   꼬리가 개를 흔드는 것이다. 거짓 경보는 거짓이라고 적고 끈다(§126).
# shellcheck disable=SC2034
PW_PIN="playwright==1.64.0"
