#!/usr/bin/env bash
# 형태소 도구 판을 **한 곳에서** 못 박는다(DECISIONS §196). `tools/lib/pw.sh` 와 같은 꼴.
#
# ★ **엔진이 둘인 것이 요점이다.** `kiwi` 는 코퍼스를 **만들고**(`tools/gen_endings.py`),
#   `mecab` 은 그것을 **읽는다**(`tools/endings_oracle.py`). 만든 엔진으로 읽으면
#   **제가 만든 답을 제가 채점하는 것**이고, `gen_endings.py` 머리말이 그것을
#   「순환이다. 그래서 사람이 본다」 로 이미 적어 뒀다. 다른 엔진이라야 증인이다.
#
# ★ **둘 다 못 박는다.** 안 박으면 어느 날 `정답` 칸이 조용히 달라지거나(kiwi) 판정이
#   색을 바꾼다(mecab). 소스를 한 줄도 안 고쳤는데 색이 바뀌는 것이 거짓 빨강이고,
#   거짓 빨강은 사람이 검사를 끄게 만든다(§126).
# ★ **`gen_endings.py` 가 이 핀 없이 돌고 있었다**(2026-10-19 에 발견). §194 가
#   playwright 에서 고친 바로 그 병이, **코퍼스를 만드는 도구**에 있었다.
#
# ★ **올릴 때는 이 줄만 고치고 한 번 돌려 본다.** 새 판이 더 많이 읽으면 사람이 볼
#   줄이 줄고 덜 읽으면 는다 — 어느 쪽이든 그 변화를 **눈으로 보고** 올린다.
#
# ★ **이 눈 밖** : 두 엔진 다 **불규칙 어간을 기본형으로 못 돌린다** — kiwi 는
#   `삽니다`(살다)를 `사다` 로, `아세요`(알다)를 감탄사로 읽었고 mecab 도 `삽니다` 를
#   `사/VV` 로 읽는다. 그래서 오라클은 **어간이 같은 동사인지는 안 묻는다.** 체(해요
#   /합쇼) · 시제 · 높임만 본다. 어간은 사람 몫이고 그것이 PLAN #66 이다.
#
# shellcheck disable=SC2034
KIWI_PIN="kiwipiepy==0.24.0"
# shellcheck disable=SC2034
MECAB_PIN="python-mecab-ko==1.3.7"

# ★ **파이썬 판도 핀이다 — 안 박으면 엔진이 아예 안 깔린다**(2026-10-19 에 재서 알았다).
#   `python-mecab-ko` 는 **cp313 휠이 하나도 없다.** 워커가 3.13 이라 `uv` 가 소스
#   빌드로 떨어지고 `RuntimeError: mecab-config not found` 로 죽는다 — 시스템 mecab 을
#   깔라는 뜻이고, 그건 검사 하나 때문에 기계에 요구할 일이 아니다.
#   **cp312 에는 manylinux 휠이 있다.** 그래서 이 자는 **제 파이썬으로 돈다** —
#   `uv run --no-project --python "$MORPH_PY"`. 워커 판과 **엮지 않는다**(엮으면 워커를
#   올릴 때 이 검사가 조용히 꺼진다).
# ★ **이 눈 밖** : 휠 표는 늙는다. `python-mecab-ko` 가 cp313 휠을 내면 이 핀을 올리고
#   **한 번 돌려 본다.** 올리는 것은 한 줄이지, 어느 날 아침 터지는 일이면 안 된다.
# shellcheck disable=SC2034
MORPH_PY="3.12"
