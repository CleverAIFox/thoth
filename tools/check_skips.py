def 둘레(줄들: list[str], i: int) -> str:
    """`i` 번째 skip 이 **어느 글 안에 있나** — 그 칸(`== ... ==`)의 첫 줄부터 그 줄까지.

    ★ **모양으로 안 본다.** 처음에 「감싸는 `if` 의 조건문」 으로 보려다 세 번째 모양에서
      깨졌다 — `ruff` 는 `command -v ruff` 가 먼저 돌아 변수를 세우고, skip 은 그
      변수로 갈린다. **도구 검사가 한 다리 건너 있다.** 모양을 하나 더 알 때마다 자를
      고치면 **자가 코드를 뒤쫓는다.**
    ★ **그래서 「그 칸 안에 그 도구를 묻는 자리가 있나」 로 묻는다.** 모양에 무관하고,
      진짜 병 — **도구를 아예 안 묻는데 `도구` 라고 적은 것** — 은 그대로 문다.
    ★ **칸은 작다.** `doctor.sh` 는 `echo "== ... =="` 로 칸을 끊고 한 칸이 수십 줄이라,
      이 창이 「아무거나 걸린다」 로 느슨해지지 않는다.
    """
    시작 = 0
    for j in range(i, -1, -1):
        if 줄들[j].lstrip().startswith('echo "== '):
            시작 = j
            break
    return "\n".join(줄들[시작 : i + 1])


def 갈래가_거짓말인가(글: str) -> list[str]:
    """선언한 갈래가 **그 자리의 모양**과 맞는가. 빈 리스트가 통과다."""
    난것: list[str] = []
    줄들 = 글.split("\n")
    for i, 줄 in enumerate(줄들):
        if 줄.lstrip().startswith("#"):
            continue
        for arg in _호출.findall(줄):
            rec = 선언.get(arg)
            if not rec:
                continue
            갈래, 근거 = rec
            그칸 = 둘레(줄들, i)
            if 갈래 == "도구":
                도구 = (_도구이름.match(근거) or [None, ""])[1]
                if f"command -v {도구}" not in 그칸:
                    난것.append(
                        f'`도구` 라고 적었는데 그 칸에 `command -v {도구}` 가 없다 : "{arg}" — **도구를 깔면 사라지는 skip 이 아니라 '
                        f"늘 도는 skip 이다")
            elif 갈래 == "범위":
                if "SCOPE" not in 그칸 and "--repo" not in 그칸:
                    난것.append(
                        f'`범위` 라고 적었는데 그 자리가 `$SCOPE` 로 갈리지 않는다 : '
                        f'"{arg}" — **범위 밖이라 안 보는 것이 아니라 늘 안 보는 것이다')
    return 난것


def fails(글: str, 산행: set[int]) -> list[str]:
    난것 = []
    본것 = 호출들(글)
    쓴것 = set()

    for arg in 본것:
        if arg not in 선언:
            난것.append(
                f'선언 안 된 skip : "{arg}" — **왜 건너뛰는지를 적는다.** '
                f"`check_skips.py` 의 `선언` 에 갈래(범위 · 도구 · 조건 · 빚)와 근거를 더한다")
            continue
        쓴것.add(arg)

    for arg in 선언:
        if arg not in 본것:
            난것.append(f'죽은 선언 : "{arg}" — `doctor.sh` 에 그 skip 이 없다. 선언에서 뺀다')

    for arg in sorted(쓴것):
        갈래, 근거 = 선언[arg]
        if 갈래 not in ("범위", "도구", "조건", "빚"):
            난것.append(f'갈래가 어휘 밖이다 : "{arg}" → {갈래}')
        if 갈래 != "빚":
            continue
        m = list(_근거참조.finditer(근거))
        if not m:
            난것.append(
                f'빚인데 근거가 없다 : "{arg}" — **닫아야 할 것은 PLAN 행이나 '
                f'DECISIONS 절을 들어야 한다.** 안 들면 영원히 노란 채로 남는다')
            continue
        for x in m:
            if x.group(1) and int(x.group(1)) not in 산행:
                난것.append(
                    f'빚이 죽은 행을 가리킨다 : "{arg}" → PLAN #{x.group(1)} 는 '
                    f"§1 에 없다. 닫혔으면 이 skip 도 없어져야 한다")

    난것 += 갈래가_거짓말인가(글)
    return 난것


_이름 = {"도구": "skip_tool", "범위": "skip_scope", "조건": "skip_cond", "빚": "skip_debt"}


def 세기(글: str) -> dict[str, int]:
    """갈래별 자리 수. **문서가 적은 수의 정본은 이 함수다**(§57 · §152).

    ★ MASTER 0-8 이 「도구 9곳 · 16곳만 본다」 를 글자로 박고 있었는데 **하루 만에
      틀렸다** — skip 하나를 더했을 뿐인데 세 수가 동시에 늙었다. §151 과 같은 병이다.
      이제 `<!--count:-->` 로 묶어 **틀리면 doctor 가 운다.**
    """
    셈: dict[str, int] = {}
    for arg in 호출들(글):
        갈래 = 선언.get(arg, ("안 선언됨", ""))[0]
        셈[갈래] = 셈.get(갈래, 0) + 1
    out = {v: 셈.get(k, 0) for k, v in _이름.items()}
    out["skip_all"] = sum(셈.values())
    # ★ **보는 것만 센다.** 「33곳을 다 본다」 로 읽히면 16곳짜리 검사를 33곳짜리로 믿는다.
    out["skip_seen"] = out["skip_tool"] + out["skip_scope"]
    return out


def _canary() -> None:
    """★ **판별식이 사나.** `skip` 호출을 못 읽으면 **본 자리가 0 건**이 되고, 그러면
    「선언 안 된 skip 이 있나」 가 **언제나 없다**로 답한다 — 꺼진 채 초록이다."""
    import sys
    본 = 호출들('skip "ㄱ"\n  skip "ㄴ"\n')
    if 본 != ["ㄱ", "ㄴ"]:
        print(f"    ★ 카나리아가 죽었다 — skip 호출을 못 읽는다 : {본}"); sys.exit(2)
    if 호출들('# skip "ㄷ" 는 글이다\n') == ["ㄷ"]:
        print("    ★ 카나리아가 죽었다 — 주석 속 글자를 호출로 센다"); sys.exit(2)


