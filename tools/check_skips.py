def 주석벗긴다(줄: str) -> str:
    """따옴표 **밖**의 `#` 부터 잘라낸다.

    ★ **종전에는 `줄.split(" #", 1)[0]` 이었다**(DECISIONS §179). 그러면 **문자열
      안의 ` #`** 도 주석 시작으로 읽혀서 `skip "… PLAN #59 가 연다"` 가 중간에서
      잘리고, `_호출` 이 안 맞아 **선언이 멀쩡히 있는데도 「죽은 선언」** 이 울었다.
      §178 과 **같은 모양**이다 — 글을 코드로 읽는 자가 **문자열을 구문으로** 읽었다.
      §178 은 `"/*"` 였고 여기는 `" #"` 다.

    ★ **그리고 이 흠은 잠복해 있었다.** 선언 서른여덟 중 ` #` 을 품은 것이 하나도
      없어서 여섯 달 동안 안 터졌다 — **맞는 것과 맞을 수밖에 없는 것은 다르다**
      (§178 의 배운 것 그대로).
    """
    안 = False
    i = 0
    while i < len(줄):
        c = 줄[i]
        if c == "\\":
            i += 2                      # 셸의 `\"` — 다음 글자는 따옴표가 아니다
            continue
        if c == '"':
            안 = not 안
        elif c == "#" and not 안 and (i == 0 or 줄[i - 1].isspace()):
            return 줄[:i]
        i += 1
    return 줄


def 호출들(글: str) -> list[str]:
    """`doctor.sh` 에 적힌 `skip "..."` 의 인자들. 주석 줄은 뺀다."""
    out = []
    for 줄 in 글.split("\n"):
        if 줄.lstrip().startswith("#"):
            continue
        out += _호출.findall(주석벗긴다(줄))
    return out


def _plan_rows() -> set[int]:
    """살아 있는 PLAN 행. 셈은 `docx_check.py` 하나다 — 두 번 세지 않는다(§132)."""
    spec = importlib.util.spec_from_file_location("docx_check", ROOT / "tools/docx_check.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m.plan_rows(ROOT)


