// 「이 페이지의 꼴이 무엇인가」 — **순수 함수만 든다**(DECISIONS §183).
//
// ★ **DOM 도 네트워크도 저장소도 안 본다.** 태그 개수 맵 하나를 받아 수를 낸다.
//   그래서 브라우저 없이 전부 시험할 수 있고, 돌연변이가 물 수 있다. 종전에는
//   `broker.js` 의 `수집만한다` 가 **지문 계산 · 적재 판단 · 로깅**을 한 몸에 했다.
//
// ★ **행 경계의 정본이 여기 하나다**(§91). 종전에는 `"tr,[role=row]"` 가
//   `cssaudit.js` · `broker.js` · `adapters/generic.js` 네 자리에 **글자로** 박혀
//   있었고, 한 자리만 고치면 나머지가 조용히 옛 값을 썼다.
//
// ★ **왜 `li` 가 덮임경계에 드는가 — 쟀다**(HTTP Archive 2026-09 · 모바일 · 1% ·
//   n≈91,000).
//
//       tr 있는 페이지      ~12%     ← 「표가 행이다」 가 덮던 전부
//       li 있는 페이지      ~76%
//       li·tr·article 합    ~87%
//
//   플랫폼 편차가 **130배**다(Framer 0.4% ↔ Weebly 52.2%). 「표가 행이다」 는
//   Udemy 를 보고 세운 가정이었고, 웹 전체에서는 **열에 아홉이 표가 없다.**
//
// ★ 밖 — **「얼마나 다른가」 는 안 쟀다.** 같은 데이터에 지문 정의만 바꾸니 61.4% 와
//   15.3% 가 나왔다. 그 수는 웹이 아니라 **내가 고른 지문**을 재고 있었다 — 그래서
//   이 판은 **모으기만 하고 값을 주장하지 않는다.**
(() => {
  const ST = (globalThis.ST ??= {});
  if (ST.꼴) return;

  // ★ **두 선택자는 다른 질문에 답한다** — 2026-10-12 에 하나로 묶으려다 멈췄다.
  //
  //   행경계    상자를 **어디에 꽂을까**. `꽂을자리` 와 행 중복 제거가 쓴다
  //   덮임경계  이 페이지 구조를 **아는가**. **수집 판정만** 쓴다
  //
  // ★ **행경계는 안 건드린다**(§133). `mount.test.js` 가 「`li` 까지 넣으면 Udemy 쪽
  //   자리가 같이 바뀐다」 고 적어 뒀고 그 말이 맞다 — 내 측정은 「구조를 아는가」 를
  //   쟀지 **「상자를 어디에 꽂을까」 는 안 쟀다.** 꽂는 자리를 바꾸려면 그 병을
  //   따로 재야 한다. **안 잰 것으로 고치지 않는다.**
  const 행경계 = "tr,[role=row]";
  const 덮임경계 = "li, tr, [role=row], article";

  // ★ **레이아웃을 이루는 태그만 센다.** SVG 내부(`path` · `circle` ·
  //   `fecolormatrix`)를 섞으면 **아이콘 세트가 다르다는 이유로 구조가 다르다**고
  //   세게 된다 — 2026-10-12 에 그 차이가 **61.4% 대 15.3%** 였다(§183).
  const 구조태그 = [
    "div", "section", "nav", "header", "footer", "main", "aside", "form",
    "p", "h1", "h2", "h3", "h4", "h5", "h6", "a", "span", "button", "img",
    "input", "label", "select", "textarea", "iframe", "video", "picture",
    "dl", "dt", "dd", "figure", "figcaption", "blockquote", "pre", "code",
  ];

  // ★ **한두 개 쓴 태그는 꼴이 아니다.** 어느 페이지에나 `div` 하나쯤은 있다.
  const 문턱 = 5;

  // ★ **`div` 가 적으면 번역할 것이 없는 페이지다**(리다이렉트 · 랜딩 · 로그인).
  //   실측 : 안 덮인 페이지의 `div` 중위값이 AMP 10 · 맨 HTML 14 · Webflow 243 로
  //   **두 덩어리로 갈렸다.** 앞쪽은 모아 봐야 배울 것이 없다(§183).
  const 최소div = 100;

  /** 태그 개수 맵 → 구조 지문. 같은 꼴이면 같은 글자가 나온다. */
  const 지문 = (개수) => {
    const m = 개수 || {};
    return 구조태그.filter((t) => (m[t] || 0) >= 문턱).join(",");
  };

  /** 이 페이지를 모을 것인가. **까닭을 같이 돌려준다** — 「안 모은다」 가 여러
   *  뜻이라 하나로 뭉치면 장부를 읽을 수 없다(DECISIONS §59). */
  const 모을까 = (개수, 덮였나) => {
    const m = 개수 || {};
    if (덮였나) return { 모은다: false, 왜: "덮였다" };
    const div = m.div || 0;
    if (div < 최소div) return { 모은다: false, 왜: `얇다(div ${div})` };
    return { 모은다: true, 왜: `안 덮였고 div ${div}` };
  };

  // ── 이 사이트에서 번역할 것인가 (DECISIONS §209) ──────────────
  //
  // ★ **수집은 필수, 번역은 선택이다.** 종전에는 `stOff` **하나**가 모든 사이트를
  //   함께 켜고 껐다. `host_permissions` 가 `<all_urls>` 이므로(§177) 한 사이트에서
  //   켜면 **지메일도 사내 시스템도 같이 켜졌다** — 2026-10-23 에 AWS 초대 메일
  //   본문이 그렇게 워커로 나갔다. 권한은 수집을 위한 것이지 번역 허락이 아니다.
  // ★ **기본은 꺼짐이다.** 지도에 없는 호스트는 수집만 돈다 — 새 사이트가 첫
  //   순회에 워커로 나가지 않는다(§183 의 「기본값으로 막는다」 와 같은 처방).
  // ★ **옛 전역 켬을 물려받지 않는다.** `stOff === false` 였던 사람도 지도는 빈
  //   채로 시작한다. 조용히 켜진 채 넘어오면 이 판이 고치려는 바로 그 일이 난다.
  // ★ **밖 — 호스트 단위다.** 같은 호스트의 다른 경로는 안 가른다. 경로에는 강의·
  //   사용자 식별자가 섞여(§131 과 같은 결) 지도가 개인 기록이 된다.
  const 사이트키 = "st번역사이트";
  const 차단키 = "stOff";          // 마스터 차단. 켜 두면 **어디서도** 번역 안 한다

  /** 이 호스트에서 번역하나. `설정` 은 `storage.local` 에서 읽은 그대로. */
  const 번역할까 = (host, 설정) => {
    if (!host) return false;
    const s = 설정 || {};
    if (s[차단키] === true) return false;
    const 지도 = s[사이트키];
    return !!(지도 && 지도[host] === true);
  };

  /** 지도에서 한 호스트를 뒤집은 **새 지도**. 원본을 안 건드린다. */
  const 뒤집는다 = (host, 지도) => {
    const m = { ...(지도 || {}) };
    if (m[host] === true) delete m[host];   // 끌 때는 **지운다** — 빈 칸이 기본이다
    else m[host] = true;
    return m;
  };

  ST.꼴 = { 행경계, 덮임경계, 구조태그, 문턱, 최소div, 지문, 모을까 };
  ST.사이트 = { 사이트키, 차단키, 번역할까, 뒤집는다 };
  // ★ 종전 자리들이 읽던 이름. 정본은 위 하나이고 이것은 **그 사본이 아니라 별명**이다.
  ST.행경계 = 행경계;
})();
