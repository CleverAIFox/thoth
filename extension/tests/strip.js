// **소스를 글자로 읽는 검사가 쓰는 주석 걷기**(DECISIONS §178).
//
// ★ **다섯 번째다.** §168 `#555` · §171 `&#39;` · §173 `127.0.0.1` 은 **주석을 코드로**
//   읽어 제 주석에 걸린 것이고, 이번은 거꾸로 **코드를 주석으로** 읽었다.
//   `popup.js` 에 이런 줄이 있다 :
//
//       ? new URL(origin).origin + "/*" : "";
//
//   문자열 안의 `"/*"` 가 블록 주석의 시작으로 읽혀서, `/\/\*[\s\S]*?\*\//` 가
//   거기서부터 다음 `*/` 까지 **코드 2,747 자를 지웠다.** 그 구간에 `쓸주소` ·
//   `쓸토큰` · `healthUrl` · `fetch(` · `127.0.0.1` 이 전부 들어 있었다 —
//   §173 이 세운 가드가 **지키려던 바로 그 자리에서 눈이 멀어 있었다.**
//   「주소가 글자로 박혀 있지 않다」 는 **그 구간을 안 보고** 초록이었다.
//
// ★ **그래서 짝 맞추기를 그만둔다.** 정규식으로 소스를 읽는 한 문법을 모르고,
//   문법을 모르는 한 문자열과 주석을 가를 수 없다. 정규식 주석 걷기는 이 집에서
//   **금지**다 — `tools/mutations.json` 의 `주석걷기` 가 그 자리를 문다.
//
// ★ **줄로 가른다.** 트림한 줄머리가 주석 기호면 그 줄을 버리고, 아니면 **줄을
//   통째로 남긴다.** 꼬리 주석은 남는다 — 그래서 꼬리 주석에 금지된 글자를 적으면
//   검사가 **운다.** 그것이 옳은 방향이다 : 거짓 양성은 고치면 되고, 거짓 음성은
//   아무도 모른다(양방향 톱니와 같은 뜻).

/** `.js` 에서 **줄 전체가 주석인 줄**만 버린다. 문자열은 절대 건드리지 않는다. */
export function 코드벗긴다(src) {
  return src
    .split("\n")
    .filter((l) => {
      const t = l.trim();
      if (t === "") return true;
      // `//` · `/*` · `*/` · JSDoc 이어지는 줄의 `*`
      return !(t.startsWith("//") || t.startsWith("/*")
               || t.startsWith("*/") || /^\*(\s|$)/.test(t));
    })
    .join("\n");
}

/** `.html` 에서 `<!-- -->` 를 버린다.
 *
 * ★ **여기서는 짝 맞추기가 성립한다.** MV3 의 기본 CSP 가 `script-src 'self'` 라
 *   이 집의 HTML 에는 **인라인 스크립트가 없고**(`popup.html` 머리글이 그 이유를
 *   적는다), 따라서 `<!--` 를 품은 문자열 리터럴이 들어올 자리가 없다.
 *   그 전제가 깨지면 — 인라인 스크립트가 생기면 — 이 함수도 못 쓴다. */
export function 글벗긴다(html) {
  return html.replace(/<!--[\s\S]*?-->/g, "");
}
