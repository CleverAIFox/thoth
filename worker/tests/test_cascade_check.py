"""`tools/cascade_check.py` 의 **판정**(DECISIONS §180).

★ **이 파일이 마지막 미선언 가드였다.** 브라우저가 있어야 도는 자라 돌연변이 사슬 밖에
  오래 서 있었다 — 그런데 **브라우저가 필요한 것은 `잰다` 하나**고, `판정` · `쓸모` ·
  `안쪽판정` 은 **행 dict 를 받는 순수 함수**다. 「못 재는 자리를 좁히고 그 자리를
  적는다」(§73) — 좁히고 보니 사각이 한 함수뿐이었다.

★ **밖 — 실제로 CSS 가 누가 이기는지는 여기서 안 본다.** 그것은 진짜 엔진이 재고
  (`잰다`), 여기서 보는 것은 **그 수를 읽는 규칙**이다.
"""
import importlib.util
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("cascade_check", ROOT / "tools/cascade_check.py")
cas = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cas)


def 행(구조="본문", 사다리="L0", 비상구="없음", 어긋남=()):
    return {"구조": 구조, "사다리": 사다리, "비상구": 비상구, "어긋남": list(어긋남)}


def 맞는판():
    """표 그대로인 행들. `이긴다` 를 정본으로 읽어 짓는다 — 수를 두 곳에 안 적는다."""
    것 = [행(사다리=L, 어긋남=() if 이김 else ("width",))
          for L, 이김 in cas.이긴다.items()]
    # 비상구 `wide` 가 구해 내는 자리를 표에 적힌 수만큼 만든다.
    for i in range(cas.비상구쓸모["wide"]):
        것.append(행(구조=f"c{i}", 사다리="L2", 비상구="없음", 어긋남=("width",)))
        것.append(행(구조=f"c{i}", 사다리="L2", 비상구="wide"))
    return 것


# ── 판정 ────────────────────────────────────────────────────────────────

def test_표대로면_조용하다():
    assert cas.판정(맞는판()) == []


def test_이길_자리에서_지면_문다():
    것 = 맞는판()
    것[0]["어긋남"] = ["display"]            # L0 은 이겨야 한다
    난것 = cas.판정(것)
    assert any("L0" in x and "졌다" in x for x in 난것)


def test_질_자리에서_이겨도_문다():
    """★ **한쪽만 보면 사이트가 약해진 것을 못 본다.** 「졌어야 할 자리가 이겼다」 는
    적수가 사라졌다는 뜻이고, 그러면 이 검사가 **때린 적 없이 초록**이 된다(§59)."""
    것 = [행(사다리="L4")]                   # L4 는 져야 한다
    assert any("L4" in x and "이겼다" in x for x in cas.판정(것))


def test_비상구가_약해지면_문다():
    것 = [r for r in 맞는판()
          if not (r["비상구"] == "wide" and r["구조"] == "c0")]
    난것 = cas.판정(것)
    assert any("wide" in x and "구해 내는 자리" in x for x in 난것)


def test_선언에_없는_비상구를_문다():
    것 = 맞는판() + [행(구조="x", 사다리="L2", 비상구="새것", 어긋남=())]
    것.append(행(구조="x", 사다리="L2", 비상구="없음", 어긋남=("width",)))
    assert any("새것" in x and "선언돼 있지 않" in x for x in cas.판정(것))


def test_선언한_비상구가_사라지면_문다():
    assert any("픽스처에 없다" in x for x in cas.판정([행()]))


# ── 쓸모 ────────────────────────────────────────────────────────────────

def test_쓸모는_구해_낸_자리만_센다():
    """★ **「비상구가 있다」 가 아니라 「없으면 지고 있으면 이긴다」 를 센다.**
    원래 이기던 자리에 붙은 비상구는 **아무도 안 구한 것**이라 0 이다."""
    것 = [행(구조="a", 사다리="L2", 어긋남=("width",)), 행(구조="a", 사다리="L2", 비상구="wide"),
          행(구조="b", 사다리="L0"), 행(구조="b", 사다리="L0", 비상구="wide")]
    assert cas.쓸모(것) == {"wide": 1}


def test_구해_내지_못하면_0_으로_선언된다():
    """★ 0 이 **없는 것**이 되면 「비상구가 사라졌다」 와 「쓸모가 0 이다」 가 같은
    말이 된다 — 다른 말이다(§59)."""
    것 = [행(구조="a", 사다리="L4", 어긋남=("width",)),
          행(구조="a", 사다리="L4", 비상구="wide", 어긋남=("width",))]
    assert cas.쓸모(것) == {"wide": 0}


# ── 안쪽 (섀도 경계) ────────────────────────────────────────────────────

def test_섀도가_새면_문다():
    것 = [{"적수": "KILL", "꼴": "섀도", "어긋남": ["display"]},
          {"적수": "없음", "꼴": "대조", "어긋남": []},
          {"적수": "없음", "꼴": "섀도", "어긋남": []},
          {"적수": "KILL", "꼴": "대조", "어긋남": ["x"] * cas.안쪽적수세기[("KILL", "대조")]}]
    assert any("섀도 경계가 샜다" in x for x in cas.안쪽판정(것))


def test_적수가_약해지면_문다():
    """★ **약해진 적수에게 안 진 섀도의 0 은 「이겼다」 가 아니라 「때린 적이 없다」 다.**"""
    것 = [{"적수": "KILL", "꼴": "대조", "어긋남": ["x"]},
          {"적수": "KILL", "꼴": "섀도", "어긋남": []},
          {"적수": "없음", "꼴": "대조", "어긋남": []},
          {"적수": "없음", "꼴": "섀도", "어긋남": []}]
    assert any("적수가 약해졌고" in x for x in cas.안쪽판정(것))


def test_안쪽_칸이_빠지면_문다():
    assert any("픽스처에 없다" in x for x in cas.안쪽판정([]))


def test_안쪽이_표대로면_조용하다():
    것 = [{"적수": "없음", "꼴": "대조", "어긋남": []},
          {"적수": "없음", "꼴": "섀도", "어긋남": []},
          {"적수": "KILL", "꼴": "섀도", "어긋남": []},
          {"적수": "KILL", "꼴": "대조", "어긋남": ["x"] * cas.안쪽적수세기[("KILL", "대조")]}]
    assert cas.안쪽판정(것) == []


# ── 못 재는 자리를 적는다 ───────────────────────────────────────────────

def test_못_잰_까닭을_삼키지_않는다():
    """★ `잰다` 는 브라우저가 있어야 돈다 — **여기서 못 보는 유일한 자리**다. 다만
    **못 잰 것을 통과로 바꾸지 않는지**는 글자로 묻는다(§59 · §70)."""
    src = (ROOT / "tools/cascade_check.py").read_text(encoding="utf-8")
    본문 = "\n".join(l for l in src.split("\n") if not l.lstrip().startswith("#"))
    몸 = 본문[본문.index("def 잰다("):본문.index("def 판정(")]
    assert 몸.count("return None, None,") >= 4, "못 잰 까닭을 가지마다 안 돌려준다"
    assert "except ImportError" in 몸, "playwright 가 없는 것을 따로 안 가른다"
