"""종결어미 교정 — 명령은 명령으로 남는다 (DECISIONS §151).

★ **규칙 셋이 명령을 평서로 바꾸고 있었다.** `먹으세요`(시켜라)가 `먹으십니다`(그가
  드신다)가 됐다 — 비문이면서 **화행까지 뒤집힌다.** 그리고 `하십시오 → 합니다` 는
  **이미 맞는 합쇼 명령을 망가뜨렸다.**

★ **코퍼스가 2,515줄로 이미 말하고 있었다** — 틀림 214 중 164 가 이 셋이다.
  `WRONG_CEILING = 214` 가 그 결함을 **기대값으로 얼려** 두고 있었다.

★ **규칙을 키우지 않는다**(§108). 셋을 **하나로 줄였다.** 남은 틀림 50 은 불규칙
  어간 복원이고 그것은 규칙을 키우는 쪽이라 §108 의 경계 밖이다.
"""
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app import engine

고치기 = engine._fix_endings


# ── 명령은 명령으로 ─────────────────────────────────────────────────────

@pytest.mark.parametrize("before,after", [
    ("먹으세요.", "먹으십시오."),
    ("그것을 읽으세요.", "그것을 읽으십시오."),
    ("데이터를 구성하세요.", "데이터를 구성하십시오."),
    ("음성을 들으세요.", "음성을 들으십시오."),
    ("그것을 주우세요.", "그것을 주우십시오."),
    ("파티션 키를 다시 설계하세요.", "파티션 키를 다시 설계하십시오."),
])
def test_세요는_십시오가_된다(before, after):
    assert 고치기(before) == after


def test_하세요도_같은_규칙이_받는다():
    # ★ 전에는 `하세요` 전용 규칙이 따로 있었고 **그것도 평서로 바꿨다.**
    #   일반 규칙이 같은 답을 내므로 전용 규칙을 지웠다 — 죽은 규칙은 안 둔다.
    assert 고치기("사용하세요.") == "사용하십시오."


# ── 이미 맞는 것은 안 건드린다 ───────────────────────────────────────────

@pytest.mark.parametrize("그대로", [
    "데이터를 암호화하십시오.",      # ★ `하십시오 → 합니다` 가 이것을 망가뜨렸다
    "그것을 설정하십시오.",
    "물으십시오.",                 # 하-가 아닌 어간도 그대로
    "그것을 부으십시오.",
    "필요한 요소를 확인합니다.",     # 이미 평서 합쇼체
    "가장 비용 효율적인 솔루션은 무엇입니까?",
    "다음 중 가장 중요한 요소",      # 명사구 — 문장이 아니다
])
def test_손대지_않는다(그대로):
    assert 고치기(그대로) == 그대로


# ── 물음표는 명령이 아니다 ──────────────────────────────────────────────

def test_물음표가_붙으면_십니까가_된다():
    # ★ `~세요?` 는 명령이 아니라 물음이다. 구두점을 안 보면 `하십시오?` 가 나온다.
    #   **코퍼스에 0건이라 안 재는 자리**이지만, 안 재는 자리에서 비문을 내지는 않는다.
    assert 고치기("사용하세요?") == "사용하십니까?"
    assert 고치기("그것을 읽으세요?") == "그것을 읽으십니까?"


# ── 마지막 줄만 본다 ────────────────────────────────────────────────────

def test_마지막_비어있지_않은_줄만_고친다():
    # ★ 기존 계약이다. 바뀌지 않았음을 못 박는다.
    assert 고치기("먹으세요.\n읽으세요.") == "먹으세요.\n읽으십시오."
    assert 고치기("읽으세요.\n\n") == "읽으십시오.\n\n"


# ── 규칙 수 ─────────────────────────────────────────────────────────────

def test_규칙을_키우지_않았다():
    # ★ §108 — 규칙 후처리는 땜질에서 멈췄다. 이 패치는 **줄였다.**
    assert len(engine._ENDINGS) <= 6, (
        f"규칙이 {len(engine._ENDINGS)}개다 — 늘리는 쪽이면 §108 을 먼저 다시 연다")
